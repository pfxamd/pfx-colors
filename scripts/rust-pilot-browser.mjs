import assert from "node:assert/strict";
import { chromium, firefox } from "playwright";

const origin = "http://127.0.0.1:4173/";

for (const [name, browserType] of [["Chromium", chromium], ["Firefox", firefox]]) {
  const browser = await browserType.launch({ headless: true });
  try {
    for (const viewport of [
      { width: 1440, height: 900 },
      { width: 390, height: 844 },
    ]) {
      for (const requested of ["legacy", "rust", "rust-workspace"]) {
        const page = await browser.newPage({ viewport });
        const errors = [];
        page.on("pageerror", error => errors.push(error.message));
        try {
          const url = requested === "legacy" ? origin : requested === "rust"
            ? origin + "?engine=rust" : origin + "?engine=rust&workspace=rust";
          const response = await page.goto(url, { waitUntil: "networkidle" });
          assert.equal(response.status(), 200);
          await page.locator(".pfx-c-home").waitFor();
          assert.equal(await page.locator(".pfx-c-study__swatch").count(), 10);
          assert.equal(await page.locator(".pfx-c-brand strong").textContent(), "PFx Colors");
          const status = await page.evaluate(() => globalThis.__pfxRustPilot ?? null);
          if (requested === "legacy") {
            assert.equal(status, null, "No Rust API should load in the default app");
          } else {
            assert.equal(status?.status, "rust", JSON.stringify(status));
            assert.ok(status?.rustCalls > 0, "Home/Picker should execute actual Rust conversions");
            assert.ok(status?.routes?.convert > 0, "Color convert must route to Rust");
            assert.ok(status?.routes?.colorStudy > 0, "Home study must be generated by real Rust WASM");
          }
          const current = page.locator('input[aria-label="Current color"]');
          assert.match(await current.inputValue(), /^#[0-9a-f]{6}$/i);
          if (requested === "rust-workspace") {
            const initialColor = await current.inputValue();
            const snapshot = () => page.evaluate(() => globalThis.__pfxRustWorkspaceDebug?.() ?? null);
            console.log("Workspace before edit:", await snapshot());
            await current.fill("#336699");
            await page.locator(".pfx-c-brand strong").click();
            assert.equal(await current.inputValue(), "#336699");
            console.log("Workspace after edit:", await snapshot());
            await page.locator(".pfx-c-history button").first().click();
            console.log("Workspace after undo:", await snapshot());
            assert.equal(await current.inputValue(), initialColor, "Rust workspace undo restores color");
            await page.locator(".pfx-c-history button").last().click();
            assert.equal(await current.inputValue(), "#336699", "Rust workspace redo restores color");
          }
          await page.locator('nav[aria-label="Color tools"] button').filter({ hasText: "Picker" }).click();
          await page.locator(".pfx-c-workbench--picker").waitFor();
          await page.locator('nav[aria-label="Color tools"] button').filter({ hasText: "Palette" }).click();
          await page.locator(".pfx-c-workbench--palette").waitFor();
          assert.ok(await page.locator(".pfx-c-palette-ribbon button").count() >= 3);
          if (requested === "rust-workspace") {
            await page.locator(".pfx-c-panel .pfx-c-action").click();
            await page.locator(".pfx-c-workbench--gradient").waitFor();
            assert.ok(await page.locator(".pfx-c-gradient-stop-handle").count() >= 3,
              "Rust workspace converts palette to gradient");
          }
          await page.locator('nav[aria-label="Color tools"] button').filter({ hasText: "Harmony" }).click();
          await page.locator(".pfx-c-workbench--harmony").waitFor();
          if (requested === "rust-workspace") {
            await page.locator('button[aria-label="Send harmony to gradient"]').click();
            await page.locator(".pfx-c-workbench--gradient").waitFor();
            assert.ok(await page.locator(".pfx-c-gradient-stop-handle").count() >= 3,
              "Rust workspace converts harmony to gradient");
          }
          await page.locator('nav[aria-label="Color tools"] button').filter({ hasText: "Gradient" }).click();
          await page.locator(".pfx-c-workbench--gradient").waitFor();
          await page.locator('button[aria-label="Add gradient stop"]').click();
          const stopsAfterAdd = await page.locator(".pfx-c-gradient-rail").locator('[role="slider"]').count();
          assert.ok(stopsAfterAdd >= 0, "Gradient remains interactive after adding a stop");
          if (requested !== "legacy") {
            const routes = await page.evaluate(() => globalThis.__pfxRustPilot?.routes ?? {});
            for (const feature of [
              "convert", "formatHex", "gamut", "mapGamut", "colorStudy",
              "tonalPalette", "harmony", "interpolate", "gradientSample",
            ]) {
              assert.ok(routes[feature] > 0, feature + " must genuinely execute in Rust WASM");
            }
            if (requested === "rust-workspace") {
              assert.ok(routes.workspace > 0, "Rust workspace must initialize and drive the UI");
            }
            console.log(name, viewport.width, "Rust routes:", JSON.stringify(routes));
          }
          const consoleResult = await page.evaluate(async () => {
            if (!globalThis.__pfxRustPilot) return null;
            const module = await import("/pfx-rust/pfx-color-core.mjs");
            const bytes = await fetch("/pfx-rust/pfx_color_ffi.wasm").then(r => r.arrayBuffer());
            const rust = await module.createPfxColorCore(bytes);
            return {
              difference: rust.difference(
                { space: "srgb", channels: [0, 0, 0], alpha: 1 },
                { space: "srgb", channels: [1, 1, 1], alpha: 1 }, "ok"),
              contrast: rust.contrast(
                { space: "srgb", channels: [0, 0, 0], alpha: 1 },
                { space: "srgb", channels: [1, 1, 1], alpha: 1 }),
              rawHue: rust.interpolate(
                { space: "hsl", channels: [350, 100, 50], alpha: 1 },
                { space: "hsl", channels: [10, 100, 50], alpha: 1 },
                0.5, { space: "hsl", hue: "raw" }).channels[0],
              shorterHue: rust.interpolate(
                { space: "hsl", channels: [350, 100, 50], alpha: 1 },
                { space: "hsl", channels: [10, 100, 50], alpha: 1 },
                0.5, { space: "hsl", hue: "shorter" }).channels[0],
            };
          });
          if (requested !== "legacy") {
            assert.ok(Math.abs(consoleResult.contrast - 21) < 1e-12);
            assert.ok(Math.abs(consoleResult.difference - 1) < 1e-7);
            assert.ok(Math.abs(consoleResult.rawHue - 180) < 1e-9);
            assert.ok(Math.abs(consoleResult.shorterHue - 0) < 1e-9);
          }
          assert.deepEqual(errors, [], name + " " + viewport.width + " " + requested);
          console.log(name, viewport.width + "x" + viewport.height, requested, "PASS");
        } finally {
          await page.close();
        }
      }
      // Simulate unavailable WASM. The same interface must remain usable with
      // the original engine, without an unhandled error or a blank page.
      const offline = await browser.newPage({ viewport });
      const offlineErrors = [];
      offline.on("pageerror", error => offlineErrors.push(error.message));
      await offline.route("**/pfx-rust/pfx_color_ffi.wasm", route => route.abort());
      await offline.goto(origin + "?engine=rust", { waitUntil: "networkidle" });
      await offline.locator(".pfx-c-home").waitFor();
      assert.equal(await offline.locator(".pfx-c-study__swatch").count(), 10);
      const fallback = await offline.evaluate(() => globalThis.__pfxRustPilot?.status);
      assert.equal(fallback, "fallback", "Unavailable WASM must use the legacy engine");
      assert.deepEqual(offlineErrors, []);
      await offline.close();
      console.log(name, viewport.width + "x" + viewport.height, "unavailable-WASM fallback PASS");
    }
  } finally {
    await browser.close();
  }
}
console.log("PFx Colors experimental Rust-WASM browser pilot: PASS");
